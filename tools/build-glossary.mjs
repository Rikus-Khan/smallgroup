// Rebuilds glossary.js from tools/glossary-terms.mjs and the verses inside every study.
// Run after adding a study or a glossary entry:  node tools/build-glossary.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import terms from "./glossary-terms.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Bible book order, from the same list the site uses
const window = {};
new Function("window", fs.readFileSync(path.join(root, "bible.js"), "utf8"))(window);
const order = Object.fromEntries(window.BIBLE_BOOKS.map(([name], k) => [name, k]));

// Every study that carries a chapter of scripture: const BOOK = "John 2"; const V = { 1: "...", ... };
const chapters = [];
for (const file of fs.readdirSync(path.join(root, "studies")).filter(f => f.endsWith(".html"))) {
  const html = fs.readFileSync(path.join(root, "studies", file), "utf8");
  const book = html.match(/const BOOK = "([^"]+?) (\d+)";/);
  const verses = html.match(/const V = (\{[\s\S]*?\n\});/);
  if (!book || !verses) continue;
  chapters.push({ book: book[1], ch: Number(book[2]), verses: new Function(`return ${verses[1]}`)() });
}
chapters.sort((a, b) => order[a.book] - order[b.book] || a.ch - b.ch);

const entries = [];
for (const t of terms) {
  if (t.match.global) throw new Error(`${t.id}: drop the /g flag from its match pattern`);
  const refs = [];
  for (const c of chapters) {
    if (t.books && !t.books.includes(c.book)) continue;
    const hits = Object.keys(c.verses).map(Number).filter(n => t.match.test(c.verses[n])).sort((a, b) => a - b);
    if (hits.length) refs.push([c.book, c.ch, hits]);
  }
  if (refs.length) entries.push({ id: t.id, kind: t.kind, name: t.name, refs });
  else console.log(`(not in any study yet: ${t.name})`);
}

const out = `// GENERATED by tools/build-glossary.mjs. Don't edit by hand:
// change tools/glossary-terms.mjs, then run  node tools/build-glossary.mjs
// refs: [book, chapter, [verses]] for every studied chapter where the entry appears
window.GLOSSARY = ${JSON.stringify(entries, null, 1).replace(/\n\s+(\d+,?)/g, " $1").replace(/\n\s+\]/g, " ]")};
`;
fs.writeFileSync(path.join(root, "glossary.js"), out);
console.log(`glossary.js: ${entries.length} entries from ${chapters.map(c => `${c.book} ${c.ch}`).join(", ")}`);
